#!/usr/bin/env python3
"""Check a generated role policy, freeze it into a run directory and write policy-comparison.md.

    python pipeline/freeze_policy.py DOMAIN POLICY RUN_DIR [--learned-access-sources 2] [--allow-no-authorities]

POLICY is a directory written by scripts/build_role_policy.py (policy.json + provenance.json)
or a policy.json path. Checks, any of which stops the freeze:

  - format gatemem-role-policy-v2 for this domain;
  - its roles are exactly the domain's job titles (the data's principal roles minus
    hosts.policy_excluded_roles), each with a description and at least one readable kind;
  - hosts.from_policy accepts it with the run's learned-access settings;
  - for hosts whose subjects never speak (office projects, education programs and
    projects) at least one authority, or no one could restrict or delete their records.

Writes into RUN_DIR: role_policy.json (byte copy), role_policy.json.sha256,
role_policy.provenance.json, policy-comparison.md. An existing different
role_policy.json is never replaced.
"""
import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

sys.path.insert(0, str(common.REPO))
sys.path.insert(0, str(common.REPO / 'scripts'))
from evaluation.gatemem_medical.hosts import HOSTS, from_policy, policy_excluded_roles  # noqa: E402
from build_role_policy import job_titles  # noqa: E402

# Runs whose hand-written role tables hosts.py still holds, shown beside the generated one.
REFERENCE_NAMES = {'medical': 'medical_domain_original', 'office': 'office_domain'}


def check(domain, raw, learned_access_sources=2, allow_no_authorities=False):
    policy = json.loads(raw)
    if policy.get('format') != 'gatemem-role-policy-v2' or policy.get('domain') != domain:
        raise SystemExit(f'not a gatemem-role-policy-v2 policy for {domain}')
    titles = job_titles(common.DATA / 'bench/data' / domain / 'episodes.jsonl', set(policy_excluded_roles(domain)))
    if sorted(policy['role_kinds']) != titles:
        raise SystemExit(f'policy roles {sorted(policy["role_kinds"])} are not the {domain} job titles {titles}')
    empty = [r for r, kinds in policy['role_kinds'].items() if not kinds]
    if empty:
        raise SystemExit(f'roles that could read nothing: {empty}')
    base = HOSTS[domain]
    host = from_policy(base, policy, policy_sha256=hashlib.sha256(raw).hexdigest(),
                       learned_access_sources=learned_access_sources, reply_access=True)
    if base.entity_kinds and not host.subject_authority_roles and not allow_no_authorities:
        raise SystemExit(f'{domain}: the policy names no authorities, so nobody could restrict or delete '
                         f'{"/".join(base.entity_kinds)} records; pass --allow-no-authorities to accept that')
    return policy, host


def comparison(domain, policy, host):
    base = HOSTS[domain]
    kinds = list(policy['information_kinds'])
    votes, n = policy['role_kind_votes'], policy['votes']
    reference = REFERENCE_NAMES.get(domain) if base.role_information_types else None
    title = domain.capitalize()
    lines = [f'# {title} role policy: generated vs original' if reference else f'# {title} role policy: generated', '',
             f"Generated by {policy['model']} (prompt v{policy['prompt_version']}), {n} votes, a cell opens with {policy['majority']} or more.",
             'Inputs: job titles from the data and the benchmark policy paragraph only. Full prompts and replies: role_policy.provenance.json.', '',
             '## Kinds of information (generated)', ''] + [f'- **{k}**: {v}' for k, v in policy['information_kinds'].items()] + [
             '', '## Job descriptions (generated, used as each role\'s scope)', ''] + [f'- **{r}**: {d}' for r, d in policy['role_descriptions'].items()]
    if reference:
        lines += ['', '## Side by side', '', f'| Role | Original ({reference}) | Generated (this run) |', '|---|---|---|']
    else:
        lines += ['', '## Role table', '', '| Role | Generated (this run) |', '|---|---|']
    for r in sorted(host.care_scopes):
        new = ', '.join(f'{k} ({votes[r][k]}/{n})' for k in kinds if k in policy['role_kinds'][r])
        old = f" {', '.join(base.role_information_types.get(r, ())) or '(no such role)'} |" if reference else ''
        lines.append(f'| {r} |{old} {new} |')
    if 'authorities' in policy:
        auth = policy.get('authority_votes', {})
        lines += ['', '## Authorities (generated)', '',
                  'Roles that may grant, restrict or delete the records of subjects that never speak '
                  f'({", ".join(base.entity_kinds) or "none in this host"}):', '',
                  ', '.join(f'{r} ({auth.get(r, "?")}/{n})' for r in policy['authorities']) or '(none)']
        if reference and base.subject_authority_roles:
            lines += ['', f'Original ({reference}): ' + ', '.join(base.subject_authority_roles)]
    lines += ['', 'Close calls (cells with 2 or 3 of 5 votes):', '']
    lines += [f'- {r} / {k}: {c}/{n}' for r in sorted(votes) for k, c in votes[r].items() if 0 < c < n and abs(c - n / 2) < 1]
    return '\n'.join(lines) + '\n'


def freeze(domain, source, run_dir, learned_access_sources=2, allow_no_authorities=False):
    source, run_dir = Path(source), Path(run_dir)
    policy_path = source / 'policy.json' if source.is_dir() else source
    provenance = policy_path.with_name('provenance.json')
    raw = policy_path.read_bytes()
    policy, host = check(domain, raw, learned_access_sources, allow_no_authorities)
    run_dir.mkdir(parents=True, exist_ok=True)
    target = run_dir / 'role_policy.json'
    if target.exists() and target.read_bytes() != raw:
        raise SystemExit(f'{target} already holds a different policy; use a new run directory')
    target.write_bytes(raw)
    digest = hashlib.sha256(raw).hexdigest()
    (run_dir / 'role_policy.json.sha256').write_text(f'{digest}  role_policy.json\n')
    if provenance.is_file():
        shutil.copyfile(provenance, run_dir / 'role_policy.provenance.json')
    (run_dir / 'policy-comparison.md').write_text(comparison(domain, policy, host))
    return digest, host


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('domain', choices=common.DOMAINS)
    ap.add_argument('policy')
    ap.add_argument('run_dir')
    ap.add_argument('--learned-access-sources', type=int, default=2)
    ap.add_argument('--allow-no-authorities', action='store_true')
    args = ap.parse_args(argv)
    digest, host = freeze(args.domain, args.policy, args.run_dir, args.learned_access_sources, args.allow_no_authorities)
    print(f'policy check ok: {dict((r, list(v)) for r, v in host.role_information_types.items())}')
    if host.subject_authority_roles:
        print(f'authorities: {list(host.subject_authority_roles)}')
    print(f'policy frozen: {digest}  role_policy.json')
    return 0


if __name__ == '__main__':
    sys.exit(main())
