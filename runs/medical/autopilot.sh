#!/usr/bin/env bash
# Unattended finish, runs in tmux window "autopilot" of session medical-new-system:
#   1. wait for the generated medical policy (restart the generator up to 2 times if it dies)
#   2. check it, freeze it as role_policy.json with a sha256, write policy-comparison.md
#   3. offline smoke test with the policy loaded (smoke-test/, outside results/)
#   4. launch.sh: all 21 episodes, 001-006 SOCLAAS, 007-021 local vLLM on GPUs 0,3
#   5. when every episode has an exit code, compile_summary.py
# Any failed check stops here and nothing is launched. Everything is logged to autopilot.log.
set -u
ROOT=/home/thaddus/v19-evaluations/medical_domain_new_system
O=/home/thaddus/a-mem-variant/evaluations/v19-role-policies
PY=/home/thaddus/gatemem/.venv-nb/bin/python
DATA=/home/thaddus/a-mem-variant/evaluations/v19/v19-model-controls-full-soclaas-20261104T103839Z/frozen-dataset
LOG=$ROOT/autopilot.log
log() { echo "$(date '+%F %T %z') $*" | tee -a "$LOG"; }
stop() { log "STOPPED: $*; nothing launched"; exit 1; }
server_up() { curl -sf -m 5 -H 'Authorization: Bearer dummy' http://127.0.0.1:18000/v1/models >/dev/null; }

log "autopilot started"
TS=$(cat $O/.ts-medical-v2); OUT=$O/medical-v2-$TS; restarts=0
while [ ! -f "$OUT/policy.json" ]; do
  if ! pgrep -f "[b]uild_role_policy.py --domain medical" >/dev/null; then
    sleep 5; [ -f "$OUT/policy.json" ] && break
    [ $restarts -ge 2 ] && stop "policy generation failed after 2 restarts (last log $OUT.log)"
    restarts=$((restarts+1)); log "generator not running and no policy in $OUT; restart $restarts"
    until server_up; do sleep 15; done
    TS=$(date -u +%Y%m%dT%H%M%SZ); OUT=$O/medical-v2-$TS; echo "$TS" > $O/.ts-medical-v2
    (cd $ROOT/frozen-source && $PY -I scripts/build_role_policy.py --domain medical --gatemem-repo /home/thaddus/GateMem \
      --exclude-roles agent,patient,family_member --base-url http://127.0.0.1:18000/v1 --model qwen3.8:27b \
      --api-key dummy --out "$OUT" > "$OUT.log" 2>&1)
    continue
  fi
  sleep 30
done
log "policy ready: $OUT"

# 2. check, freeze, compare
cp "$OUT/policy.json" $ROOT/role_policy.json && cp "$OUT/provenance.json" $ROOT/role_policy.provenance.json || stop "copy failed"
(cd $ROOT && sha256sum role_policy.json > role_policy.json.sha256)
(cd $ROOT/frozen-source && $PY -I - <<'EOF') >> "$LOG" 2>&1 || stop "policy check failed (see autopilot.log)"
import hashlib, json, sys
sys.path.insert(0, '.')
from evaluation.gatemem_medical.hosts import MEDICAL, from_policy
root = '/home/thaddus/v19-evaluations/medical_domain_new_system'
raw = open(root + '/role_policy.json', 'rb').read(); p = json.loads(raw)
host = from_policy(MEDICAL, p, policy_sha256=hashlib.sha256(raw).hexdigest(), learned_access_sources=2, reply_access=True)
assert set(host.care_scopes) == set(MEDICAL.care_scopes), f'roles differ: {sorted(host.care_scopes)}'
assert all(host.role_information_types[r] for r in host.care_scopes), 'a role can read nothing'
kinds = list(p['information_kinds'])
lines = ['# Medical role policy: generated vs original', '',
         f"Generated by {p['model']} (prompt v{p['prompt_version']}), {p['votes']} votes, a cell opens with {p['majority']} or more.",
         'Inputs: job titles from the data and the benchmark policy paragraph only. Full prompts and replies: role_policy.provenance.json.', '',
         '## Kinds of information (generated)', ''] + [f'- **{k}**: {v}' for k, v in p['information_kinds'].items()] + [
         '', '## Job descriptions (generated, used as each role\'s scope)', ''] + [f'- **{r}**: {d}' for r, d in p['role_descriptions'].items()] + [
         '', '## Side by side', '', '| Role | Original (medical_domain_original) | Generated (this run) |', '|---|---|---|']
for r in sorted(host.care_scopes):
    votes = p['role_kind_votes'][r]
    new = ', '.join(f'{k} ({votes[k]}/{p["votes"]})' for k in kinds if k in p['role_kinds'][r])
    lines.append(f"| {r} | {', '.join(MEDICAL.role_information_types[r])} | {new} |")
lines += ['', 'Close calls (cells with 2 or 3 of 5 votes):', '']
lines += [f'- {r} / {k}: {n}/{p["votes"]}' for r in sorted(p['role_kind_votes']) for k, n in p['role_kind_votes'][r].items() if 0 < n < p['votes'] and abs(n - p['votes'] / 2) < 1]
open(root + '/policy-comparison.md', 'w').write('\n'.join(lines) + '\n')
print('policy check ok:', {r: list(v) for r, v in host.role_information_types.items()})
EOF
log "policy frozen: $(cat $ROOT/role_policy.json.sha256)"

# 3. offline smoke test with this policy
rm -rf $ROOT/smoke-test; mkdir -p $ROOT/smoke-test
(cd $ROOT/frozen-source && env PYTHONDONTWRITEBYTECODE=1 CUDA_VISIBLE_DEVICES= timeout 1800 $PY -m evaluation.gatemem_medical --offline \
  --env-file $ROOT/model.env --gatemem-repo $DATA --permission-mode inference --permission-version 19 --answer-validation-mode enforce \
  --role-policy $ROOT/role_policy.json --learned-access-sources 2 --reply-access --episode-contains _001_ --max-boundaries 2 \
  --run-dir $ROOT/smoke-test/run > $ROOT/smoke-test/run.log 2>&1) || stop "offline smoke test failed (smoke-test/run.log)"
want="policy-sha256:$(cut -d' ' -f1 $ROOT/role_policy.json.sha256)"
got=$($PY -c "import json; print(json.load(open('$ROOT/smoke-test/run/manifest.json'))['access_policy']['role_tables'])")
[ "$got" = "$want" ] || stop "smoke test loaded a different policy ($got)"
log "offline smoke test passed"

# 4. launch
until server_up; do log "waiting for local vLLM"; sleep 30; done
bash $ROOT/launch.sh >> "$LOG" 2>&1 || stop "launch.sh refused (see autopilot.log)"
log "launched all 21 episodes"

# 5. summary when every episode has finished
while [ "$(ls $ROOT/results/*/exit-code.txt 2>/dev/null | wc -l)" -lt 21 ]; do sleep 300; done
log "all 21 episodes have exit codes: $(cat $ROOT/results/*/exit-code.txt | sort | uniq -c | tr '\n' ' ')"
(cd $ROOT && $PY compile_summary.py) >> "$LOG" 2>&1 && log "summary written: $ROOT/summary.json" || log "compile_summary.py failed"
